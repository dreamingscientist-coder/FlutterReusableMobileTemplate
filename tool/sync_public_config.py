#!/usr/bin/env python3
"""Build public settings from saved legal configuration and verified store identities."""
import argparse
import importlib.util
import json
from pathlib import Path
import re
import sys
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = {'SUPPORT_EMAIL', 'SUPPORT_URL', 'PRIVACY_URL', 'TERMS_URL', 'DATA_DELETION_URL', 'WEBSITE_URL', 'RATE_APP_URL', 'SHARE_APP_URL', 'MORE_APPS_URL'}


def env_values(path):
    result = {}
    if path.exists():
        for raw in path.read_text().splitlines():
            if '=' not in raw or raw.lstrip().startswith('#'):
                continue
            key, value = raw.split('=', 1)
            result[key.strip()] = value.strip().strip('\"\'')
    return result


def write_changed(path, data):
    content = json.dumps(data, indent=2) + '\n'
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def build_links(root, platform, store):
    links = {key: value for key, value in env_values(root / 'app_links.env').items() if key in PUBLIC}
    saved = env_values(root / 'app.env')
    saved.update(env_values(root / '.env'))
    base = saved.get('LEGAL_URL', '').rstrip('/')
    if base.startswith('https://'):
        links.update({'SUPPORT_URL': base + '/support.html', 'PRIVACY_URL': base + '/privacy.html',
                      'TERMS_URL': base + '/terms.html', 'DATA_DELETION_URL': base + '/privacy.html',
                      'WEBSITE_URL': base})
    if saved.get('SUPPORT_EMAIL'):
        links['SUPPORT_EMAIL'] = saved['SUPPORT_EMAIL']
    links.update({key: value for key, value in store.get(platform, {}).items() if key in PUBLIC and value})
    # A developer action must stay in the platform's store. Never use legal pages.
    developer = saved.get('APPLE_DEVELOPER_URL' if platform == 'ios' else 'GOOGLE_DEVELOPER_URL', '')
    if developer:
        links['MORE_APPS_URL'] = developer
    expected_host = 'apps.apple.com' if platform == 'ios' else 'play.google.com'
    from urllib.parse import urlparse
    if urlparse(links.get('MORE_APPS_URL', '')).netloc != expected_host:
        links['MORE_APPS_URL'] = ''
    return links


def identities(root):
    ios = (root / 'ios/Runner.xcodeproj/project.pbxproj').read_text()
    bundles = set(re.findall(r'PRODUCT_BUNDLE_IDENTIFIER\s*=\s*"?([\w.-]+)', ios))
    bundles = {bundle for bundle in bundles if not bundle.endswith('.RunnerTests')}
    if len(bundles) != 1:
        raise ValueError('Expected one Runner bundle ID')
    gradle = next(root / 'android/app' / name for name in ('build.gradle.kts', 'build.gradle') if (root / 'android/app' / name).exists())
    match = re.search(r'applicationId\s*(?:=\s*)?[\'"]([\w.]+)', gradle.read_text())
    if not match:
        raise ValueError('Expected a literal Android applicationId')
    return {'ios': bundles.pop(), 'android': match[1]}


def refresh_store(root, store, platforms):
    ids = identities(root)
    helper = Path.home() / 'Developer/Tool/ggad_store_identity.py'
    spec = importlib.util.spec_from_file_location('ggad_store', helper)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    selected = {}
    for platform in platforms:
        identity = ids[platform]
        current = store.get(platform, {})
        try:
            if platform == 'android':
                if identity.startswith('com.example.'):
                    raise ValueError('Android still has a placeholder package name')
                app = {'identity': identity, 'store_id': identity}
            else:
                app_id = current.get('store_id') if current.get('identity') == identity else None
                if not app_id:
                    match = re.search(r'/id([0-9]+)', current.get('SHARE_APP_URL', '')) if current.get('identity') == identity else None
                    app_id = match[1] if match else None
                if app_id:
                    app = {'identity': identity, 'store_id': app_id}
                else:
                    matches = [app for app in module.store_apps('ios') if app['identity'] == identity]
                    if len(matches) != 1:
                        raise ValueError('No unique App Store Connect app matches the bundle ID')
                    app = matches[0]
            selected[platform] = app
        except Exception as error:
            print(f'{platform} store lookup unavailable ({type(error).__name__}); retaining current identity links.', file=sys.stderr)
    return module.sync_store_links(root, selected, prompt=True)


def write_project_defaults(root, store):
    defaults = {platform: build_links(root, platform, store) for platform in ('ios', 'android')}
    content = '// Generated by gprivacy / sync_public_config.py. Public values only.\n'
    for platform, links in defaults.items():
        content += f'const {platform}PublicDefaults = <String, String>{{\n'
        for key, value in sorted(links.items()):
            literal = json.dumps(value, ensure_ascii=False).replace('$', r'\$')
            content += f'  "{key}": {literal},\n'
        content += '};\n'
    store_config = root / 'lib/services/store_links_config.dart'
    if store_config.exists():
        fields = {'appleAppUrl': defaults['ios'].get('SHARE_APP_URL', ''),
                  'googleAppUrl': defaults['android'].get('SHARE_APP_URL', ''),
                  'appleDeveloperUrl': defaults['ios'].get('MORE_APPS_URL', ''),
                  'googleDeveloperUrl': defaults['android'].get('MORE_APPS_URL', '')}
        text = '// Generated public store defaults; no private credentials.\nclass StoreLinksConfig {\n'
        for key, value in fields.items():
            text += f'  static const {key} = ' + json.dumps(value).replace('$', r'\$') + ';\n'
        text += '}\n'
        store_config.write_text(text)
    path = root / 'lib/config/public_defaults.dart'
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def synchronize(root, store):
    for platform in ('ios', 'android'):
        source = root / f'admob_{platform}_defines.json'
        ads = json.loads(source.read_text()) if source.exists() else {}
        values = {key: value for key, value in ads.items() if key.startswith(f'ADMOB_{platform.upper()}_')}
        values.update(build_links(root, platform, store))
        write_changed(root / f'release_{platform}_defines.json', values)
    write_project_defaults(root, store)
    print('Public project defaults and release settings synchronized from saved legal and store links.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh-store', action='store_true')
    parser.add_argument('--platform', choices=['ios', 'android'])
    args = parser.parse_args()
    path = ROOT / 'store_links.json'
    store = json.loads(path.read_text()) if path.exists() else {}
    # Prevent a changed bundle/package from inheriting links belonging to another app.
    for platform, identity in identities(ROOT).items():
        if store.get(platform, {}).get('identity') != identity:
            store.pop(platform, None)
    if args.refresh_store:
        store = refresh_store(ROOT, store, [args.platform] if args.platform else ['ios', 'android'])
    synchronize(ROOT, store)
